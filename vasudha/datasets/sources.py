def get_dataset_source(name: str) -> DatasetSource:
    """
    Retrieve a dataset source by registry alias or HuggingFace ID.

    The configs refer to datasets by their full HF ID ("open-thoughts/OpenThoughts3")
    while the registry is keyed by short alias ("openthoughts3"), so both are
    accepted. An unregistered HF ID is usable too — it just has to declare its
    schema, which the registry would otherwise supply.
    """
    if name in DATASET_REGISTRY:
        return DATASET_REGISTRY[name]

    # Reverse lookup: the config gave a full HF ID for a registered dataset.
    for source in DATASET_REGISTRY.values():
        if source.name == name:
            return source

    if "/" in name:
        logger.warning(
            f"Dataset '{name}' is not in the registry — assuming a plain 'text' "
            "column. Register it with register_dataset() if it uses conversations "
            "or messages, otherwise examples will be dropped as empty."
        )
        return DatasetSource(name=name)

    raise ValueError(
        f"Dataset source '{name}' not found in registry. "
        f"Known aliases: {sorted(DATASET_REGISTRY)}. "
        "Full HuggingFace IDs (e.g. 'org/dataset') are also accepted."
    )

def list_datasets() -> list[str]:
    """List all registered dataset sources."""
    return list(DATASET_REGISTRY.keys())

def register_dataset(name: str, source: DatasetSource) -> None:
    """Register a new dataset source."""
    if name in DATASET_REGISTRY:
        logger.warning(f"Overwriting existing dataset source '{name}'.")
    DATASET_REGISTRY[name] = source
